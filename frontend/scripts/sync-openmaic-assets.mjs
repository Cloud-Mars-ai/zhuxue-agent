#!/usr/bin/env node
/**
 * 同步 OpenMAIC 提示词资产（sync-openmaic-assets.mjs）
 *
 * 职责：
 * 1. 若存在 vendor/openmaic 浅克隆，把 @openmaic/generation 的 templates/ 与
 *    snippets/ 复制到 src/api/openmaic/assets/（入库，作为唯一事实源）；
 * 2. 无论 vendor 是否存在，都从 assets/*.md 重新生成 promptAssets.js
 *    （内嵌字符串资产，浏览器打包与 node 测试双可用——OpenMAIC 上游用
 *    node:fs 读模板，浏览器端不可用，这是接入的关键适配）。
 *
 * 用法：node scripts/sync-openmaic-assets.mjs [--check]
 *   --check  只校验资产与生成物是否同步，不写文件（CI 用）
 */

import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync, statSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const FRONTEND_ROOT = resolve(HERE, '..')
const ASSETS_DIR = join(FRONTEND_ROOT, 'src/api/openmaic/assets')
const GENERATED = join(FRONTEND_ROOT, 'src/api/openmaic/promptAssets.js')
const VENDOR = join(FRONTEND_ROOT, '../vendor/openmaic/packages/@openmaic/generation')

const TEMPLATE_IDS = [
  'requirements-to-outlines',
  'slide-content',
  'quiz-content',
  'simulation-content',
]

const checkOnly = process.argv.includes('--check')

function ensureDir(dir) {
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true })
}

function copyFromVendor() {
  if (!existsSync(VENDOR)) {
    console.log('[sync] vendor/openmaic 不存在，跳过复制（使用库内 assets）')
    return false
  }
  let copied = 0
  for (const id of TEMPLATE_IDS) {
    const srcDir = join(VENDOR, 'templates', id)
    const dstDir = join(ASSETS_DIR, 'templates', id)
    ensureDir(dstDir)
    for (const file of ['system.md', 'user.md']) {
      const src = join(srcDir, file)
      if (!existsSync(src)) continue
      const content = readFileSync(src, 'utf-8')
      const dst = join(dstDir, file)
      if (!existsSync(dst) || readFileSync(dst, 'utf-8') !== content) {
        if (!checkOnly) writeFileSync(dst, content)
        copied += 1
      }
    }
  }
  const snippetSrc = join(VENDOR, 'snippets')
  const snippetDst = join(ASSETS_DIR, 'snippets')
  ensureDir(snippetDst)
  for (const file of readdirSync(snippetSrc)) {
    if (!file.endsWith('.md')) continue
    const content = readFileSync(join(snippetSrc, file), 'utf-8')
    const dst = join(snippetDst, file)
    if (!existsSync(dst) || readFileSync(dst, 'utf-8') !== content) {
      if (!checkOnly) writeFileSync(dst, content)
      copied += 1
    }
  }
  console.log(`[sync] vendor → assets：${copied} 个文件${checkOnly ? '待同步' : '已更新'}`)
  return copied > 0
}

function readAsset(relPath) {
  const full = join(ASSETS_DIR, relPath)
  if (!existsSync(full)) return null
  return readFileSync(full, 'utf-8')
}

function jsString(value) {
  return JSON.stringify(value)
}

function buildGenerated() {
  const templates = {}
  for (const id of TEMPLATE_IDS) {
    const system = readAsset(join('templates', id, 'system.md'))
    const user = readAsset(join('templates', id, 'user.md'))
    if (system == null) throw new Error(`缺少模板资产：templates/${id}/system.md`)
    templates[id] = { system, user: user ?? '' }
  }
  const snippets = {}
  const snippetDir = join(ASSETS_DIR, 'snippets')
  if (existsSync(snippetDir)) {
    for (const file of readdirSync(snippetDir)) {
      if (!file.endsWith('.md')) continue
      snippets[file.replace(/\.md$/, '')] = readFileSync(join(snippetDir, file), 'utf-8')
    }
  }
  const banner =
    '// AUTO-GENERATED by scripts/sync-openmaic-assets.mjs — 请勿手改，改 assets/*.md 后重新生成\n' +
    '// 上游来源：THU-MAIC/OpenMAIC packages/@openmaic/generation（MIT）\n' +
    '// 上游快照：commit 5bd8cc8（tag v0.3.29 之后主线，2026-11-07 拉取）；\n' +
    '// vendor/openmaic 为本地快照克隆（已 gitignore），可复现性以本 commit + assets/ 为准\n'
  const body =
    `${banner}\nexport const OPENMAIC_TEMPLATES = ${jsString(templates)}\n\n` +
    `export const OPENMAIC_SNIPPETS = ${jsString(snippets)}\n\n` +
    `export const OPENMAIC_ASSET_VERSION = 'openmaic-0.3.29-adapt'\n`
  return body
}

async function main() {
  ensureDir(ASSETS_DIR)
  const vendorChanged = copyFromVendor()
  const generated = buildGenerated()
  const current = existsSync(GENERATED) ? readFileSync(GENERATED, 'utf-8') : null
  if (current === generated) {
    console.log('[sync] promptAssets.js 已是最新')
    if (checkOnly && vendorChanged) {
      console.error('[sync][check] assets/*.md 与 vendor 不同步')
      process.exit(1)
    }
    return
  }
  if (checkOnly) {
    console.error('[sync][check] promptAssets.js 过期，请运行 node scripts/sync-openmaic-assets.mjs')
    process.exit(1)
  }
  ensureDir(dirname(GENERATED))
  writeFileSync(GENERATED, generated)
  const { OPENMAIC_TEMPLATES, OPENMAIC_SNIPPETS } = await import(GENERATED)
  console.log(
    `[sync] promptAssets.js 已生成：${Object.keys(OPENMAIC_TEMPLATES).length} 模板（${Object.keys(OPENMAIC_TEMPLATES).join(', ')}），${Object.keys(OPENMAIC_SNIPPETS).length} snippets`,
  )
}

await main()
