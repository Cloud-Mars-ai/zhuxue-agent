import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const dataDir = resolve(scriptDir, '../src/competition/official')
const outputFile = resolve(dataDir, 'raw-sources.generated.js')

const sources = {
  curriculumCsv: 'curriculum.csv',
  questionsMaterialsCsv: 'questions-materials.csv',
  studentsCsv: 'students.csv',
  assessmentNodesCsv: 'assessment-nodes.csv',
  responsesCsv: 'responses.csv',
  fieldsCsv: 'fields.csv',
}

const lines = [
  '// Generated by scripts/sync-competition-data.mjs. Do not edit by hand.',
]
for (const [variable, filename] of Object.entries(sources)) {
  const content = await readFile(resolve(dataDir, filename), 'utf8')
  lines.push(`export const ${variable} = ${JSON.stringify(content)}`)
}
await writeFile(outputFile, `${lines.join('\n')}\n`, 'utf8')
console.log(`Synced ${Object.keys(sources).length} official CSV files to ${outputFile}`)
