/** 只输出 JSON 的硬约束（用于需要解析的任务） */
export function jsonOnly(schemaText) {
  return `输出要求：只输出一个 JSON 对象，不要 Markdown 代码块，不要前后解释。结构如下：\n${schemaText}`
}
