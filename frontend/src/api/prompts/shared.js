/** 学生学科背景（M5 差异化引擎） */
export function disciplineHint(discipline) {
  if (discipline === '工科类') {
    return '这名学生是工科背景、选修本课：举例优先用工程管理、生产现场、项目协作的场景。'
  }
  if (discipline === '管理类') {
    return '这名学生是管理类背景：可以用典型企业管理场景，但不要停在常识层面。'
  }
  if (discipline) {
    return `这名学生的学科背景是"${discipline}"：请选择他能代入的场景。`
  }
  return '这名学生的学科背景未填写：用通用、跨领域的例子。'
}

